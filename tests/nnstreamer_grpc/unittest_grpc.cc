/**
 * @brief Add a uint8 tensor holding @a data to a protobuf message.
 */
static void
_pb_add_tensor (PbTensors &msg, const std::string &data)
{
  nnstreamer::protobuf::Tensor *tensor = msg.add_tensor ();

  tensor->set_name ("test");
  tensor->set_type (nnstreamer::protobuf::Tensor::NNS_UINT8);
  tensor->add_dimension (data.size ());
  tensor->set_data (data);
}

/**
 * @brief Build a protobuf message that fits RECV_STATIC_CAPS.
 */
