/**
 * @brief Build a gRPC element and bring it to PAUSED, where start () has run.
 * @return the state change result; the element is returned in @a element
 */
static GstStateChangeReturn
_start_grpc_element (const gchar *name, const gchar *host, GstElement **element)
{
  GstElement *e = gst_element_factory_make (name, NULL);

  if (!e)
    return GST_STATE_CHANGE_FAILURE;

  g_object_set (e, "server", (gboolean) TRUE, "host", host, "port", 0, NULL);
  *element = e;

  return gst_element_set_state (e, GST_STATE_PAUSED);
}

/**
 * @brief Wait until the source pad of @a element has negotiated its caps.
 */
static gboolean
_wait_for_caps (GstElement *element)
{
  GstPad *pad = gst_element_get_static_pad (element, "src");
  GstCaps *caps = NULL;
  guint i;

  for (i = 0; i < 1000 && !caps; i++) {
    caps = gst_pad_get_current_caps (pad);
    if (!caps)
      g_usleep (10000);
  }
  gst_object_unref (pad);

  if (!caps)
    return FALSE;

  gst_caps_unref (caps);
  return TRUE;
}

