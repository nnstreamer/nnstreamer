_pb_valid_static (void)
{
  PbTensors msg;

  msg.set_num_tensor (2);
  _pb_add_tensor (msg, std::string (4, '\x01'));
  _pb_add_tensor (msg, std::string (2, '\x02'));
  return msg;
}

/**
 * @brief Send @a msgs over one client-streaming call of the protobuf service.
 */
static void
_pb_send (const std::string &address, const std::function<void ()> &wait,
    const std::vector<PbTensors> &msgs)
{
  auto stub = nnstreamer::protobuf::TensorService::NewStub (
      grpc::CreateChannel (address, grpc::InsecureChannelCredentials ()));
  grpc::ClientContext context;
  google::protobuf::Empty reply;
  auto writer = stub->SendTensors (&context, &reply);

  for (const PbTensors &msg : msgs)
    writer->Write (msg);
  writer->WritesDone ();
  wait ();
  writer->Finish ();
}

