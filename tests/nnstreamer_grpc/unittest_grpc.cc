using FbTensors = nnstreamer::flatbuf::Tensors;
using FbMessage = flatbuffers::grpc::Message<FbTensors>;

/**
 * @brief Build a flatbuf message with uint8 tensors of @a data_sizes bytes.
 * @param data_sizes A negative size leaves the data field of that tensor out; NULL leaves the tensor vector out.
 */
static FbMessage
_fb_build (gint num_tensor, const std::vector<gint> *data_sizes)
{
  flatbuffers::grpc::MessageBuilder builder;
  std::vector<flatbuffers::Offset<nnstreamer::flatbuf::Tensor>> tensors;
  nnstreamer::flatbuf::frame_rate fr (30, 1);
  guint32 dim[NNS_TENSOR_RANK_LIMIT] = { 0 };
  flatbuffers::Offset<flatbuffers::Vector<flatbuffers::Offset<nnstreamer::flatbuf::Tensor>>> vec;

  if (data_sizes) {
    for (gint size : *data_sizes) {
      std::vector<guint8> bytes (size > 0 ? size : 0, 1);
      auto name = builder.CreateString ("test");
      auto dims = builder.CreateVector (dim, NNS_TENSOR_RANK_LIMIT);
      flatbuffers::Offset<flatbuffers::Vector<guint8>> data;

      if (size >= 0)
        data = builder.CreateVector (bytes);

      tensors.push_back (nnstreamer::flatbuf::CreateTensor (builder, name,
          nnstreamer::flatbuf::Tensor_type_NNS_UINT8, dims, data));
    }
    vec = builder.CreateVector (tensors);
  }

  builder.Finish (nnstreamer::flatbuf::CreateTensors (builder, num_tensor, &fr, vec));
  return builder.ReleaseMessage<FbTensors> ();
}

/**
 * @brief Send @a msgs over one client-streaming call of the flatbuf service.
 */
static void
_fb_send (const std::string &address, const std::function<void ()> &wait,
    std::vector<FbMessage> &msgs)
{
  auto stub = nnstreamer::flatbuf::TensorService::NewStub (
      grpc::CreateChannel (address, grpc::InsecureChannelCredentials ()));
  grpc::ClientContext context;
  flatbuffers::grpc::Message<nnstreamer::flatbuf::Empty> reply;
  auto writer = stub->SendTensors (&context, &reply);

  for (FbMessage &msg : msgs)
    writer->Write (msg);
  writer->WritesDone ();
  /* Finish () of a flatbuf client-streaming call aborts, see SyncServiceImplFlatbuf::_client_thread (). */
  wait ();
}

/**
 * @brief Run a flatbuf receive test on RECV_STATIC_CAPS: the given message (if @a with_bad), then a valid one.
 */
static guint
_fb_recv (gboolean with_bad, gint num_tensor,
    const std::vector<gint> *data_sizes, std::vector<gsize> &sizes)
{
  const std::vector<gint> valid = { 4, 2 };

  return _run_recv_test (
      "flatbuf", RECV_STATIC_CAPS,
      [&] (const std::string &addr, const std::function<void ()> &wait) {
        std::vector<FbMessage> msgs;
        if (with_bad)
          msgs.push_back (_fb_build (num_tensor, data_sizes));
        msgs.push_back (_fb_build (2, &valid));
        _fb_send (addr, wait, msgs);
      },
      1, sizes);
}

